#!/usr/bin/env node
/**
 * Generates both `.dev.vars` files from the single `secrets.json`.
 *
 * The two Workers share DB_ENCRYPTION_KEY, AUTH_TWITTER_ID and AUTH_TWITTER_SECRET,
 * and those values must be byte-identical — a mismatched DB_ENCRYPTION_KEY means the
 * scheduler cannot decrypt stored OAuth tokens. Generating both files from one source
 * makes that drift impossible locally, the same way `npm run secrets:push` does in
 * production.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(repoRoot, 'secrets.json');

/** Which keys each Worker actually reads. Keep in sync with the wrangler.jsonc comments. */
const TARGETS = [
  {
    file: join(repoRoot, 'packages/simply-tweeted-app/.dev.vars'),
    keys: [
      'AUTH_SECRET',
      'DB_ENCRYPTION_KEY',
      'AUTH_TWITTER_ID',
      'AUTH_TWITTER_SECRET',
      'ALLOWED_TWITTER_ACCOUNTS'
    ]
  },
  {
    file: join(repoRoot, 'packages/scheduler/.dev.vars'),
    keys: ['DB_ENCRYPTION_KEY', 'AUTH_TWITTER_ID', 'AUTH_TWITTER_SECRET']
  }
];

let secrets;
try {
  secrets = JSON.parse(readFileSync(source, 'utf8'));
} catch (error) {
  const reason = error.code === 'ENOENT' ? 'not found' : `unreadable (${error.message})`;
  console.error(`secrets.json ${reason}.`);
  console.error('Create it first:  cp secrets.example.json secrets.json');
  process.exit(1);
}

const missing = [...new Set(TARGETS.flatMap((t) => t.keys))].filter((key) => !secrets[key]);
if (missing.length > 0) {
  console.error(`secrets.json is missing values for: ${missing.join(', ')}`);
  process.exit(1);
}

for (const { file, keys } of TARGETS) {
  const body = keys.map((key) => `${key}=${secrets[key]}`).join('\n');
  writeFileSync(file, `# Generated by npm run secrets:local — edit secrets.json, not this.\n${body}\n`);
  console.log(`wrote ${relative(repoRoot, file)} (${keys.length} keys)`);
}
